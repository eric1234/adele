import 'dart:convert';
import 'dart:io';

// This is a reviewed inventory for this native package, not an SPDX resolver.
const reviewedLockSha256 =
    '2d99311ce98608332b871c4b72d105ccb278486b8c67bd484a81d72022fc03c9';
const rustVersion = '1.93.0';
const rustCommit = '254b59607d4417e9dffbc307138ae5c86280fe4c';
const target = 'x86_64-unknown-linux-gnu';
final noticeSeparator = '\n${'-' * 80}\n';

void main(List<String> arguments) {
  try {
    if (arguments.length > 1 ||
        (arguments.isNotEmpty && arguments.single != '--check')) {
      throw StateError('Usage: dart tool/generate_notices.dart [--check]');
    }
    final package = File.fromUri(Platform.script).parent.parent;
    final generated = generateNotices(package);
    final output = File('${package.path}/LICENSE');
    final current = output.existsSync() ? output.readAsStringSync() : null;
    if (arguments.contains('--check')) {
      if (current != generated) {
        throw StateError(
          'LICENSE is missing/stale; run tool/generate_notices.dart',
        );
      }
      stdout.writeln('Credential third-party notices are current.');
    } else {
      if (current != generated) output.writeAsStringSync(generated);
      stdout.writeln(
        'Generated LICENSE (${utf8.encode(generated).length} bytes).',
      );
    }
  } on Object catch (error) {
    stderr.writeln('Notice generation failed: $error');
    exitCode = 1;
  }
}

String generateNotices(Directory package) {
  final native = Directory('${package.path}/native');
  final lock = File('${native.path}/Cargo.lock');
  if (sha256File(lock) != reviewedLockSha256) {
    throw StateError(
      'Cargo.lock changed; review crate licenses and supplemental '
      'notices before updating reviewedLockSha256.',
    );
  }
  if (File('${native.path}/rust-toolchain').readAsStringSync().trim() !=
      rustVersion) {
    throw StateError('Unreviewed Rust toolchain; runtime notices need review.');
  }
  final compiler = _run('rustup', ['run', rustVersion, 'rustc', '-vV']);
  if (!compiler.contains('commit-hash: $rustCommit\n') ||
      !compiler.contains('host: $target\n')) {
    throw StateError('Not the reviewed Rust $rustVersion Linux x64 compiler.');
  }

  final metadata = _metadata(native);
  final packages = (metadata['packages'] as List).cast<Map<String, dynamic>>();
  final own = packages.where((p) => p['source'] == null).toList();
  if (own.length != 1 || own.single['name'] != 'adele_credential_store') {
    throw StateError('Unexpected native workspace/path dependency.');
  }
  final crates = packages.where((p) => p['source'] != null).toList();
  final checksums = lockChecksums(lock.readAsStringSync());
  if (crates.length != 116 || crates.length != checksums.length) {
    throw StateError('Incomplete locked native inventory.');
  }
  crates.sort(_comparePackages);

  final sysroot = Directory(
    _run('rustup', ['run', rustVersion, 'rustc', '--print', 'sysroot']).trim(),
  );
  final library = Directory('${sysroot.path}/lib/rustlib/src/rust/library');
  final docs = Directory('${sysroot.path}/share/doc/rust');
  if (!File('${library.path}/Cargo.lock').existsSync() ||
      !File('${docs.path}/COPYRIGHT-library.html').existsSync()) {
    throw StateError(
      'Install runtime notice sources: rustup component add '
      'rust-src rust-docs --toolchain $rustVersion',
    );
  }
  // rust-src uses Cargo's unstable public-dependency syntax. This enables only
  // metadata parsing of the pinned upstream manifest, never a build or rustc.
  final runtime = _metadata(library, runtime: true);
  final runtimePackages = (runtime['packages'] as List)
      .cast<Map<String, dynamic>>();
  final root = runtimePackages.singleWhere((p) => p['name'] == 'std');
  final nodes = {
    for (final node in runtime['resolve']['nodes'] as List)
      node['id'] as String: node as Map<String, dynamic>,
  };
  final reached = <String>{};
  void visit(String id) {
    if (!reached.add(id)) return;
    for (final dep in nodes[id]!['deps'] as List) {
      if ((dep['dep_kinds'] as List).any((k) => k['kind'] != 'dev')) {
        visit(dep['pkg'] as String);
      }
    }
  }

  visit(root['id'] as String);
  final runtimeCrates =
      runtimePackages
          .where((p) => reached.contains(p['id']) && p['source'] != null)
          .toList()
        ..sort(_comparePackages);
  final runtimeChecksums = lockChecksums(
    File('${library.path}/Cargo.lock').readAsStringSync(),
  );

  final sections = <String>[
    'adele_credential_store third-party inventory\n\n'
        'THIRD-PARTY NOTICES ONLY\n'
        'This file does NOT license ADELE source or assign ADELE a license.\n'
        'It records upstream terms for the native credential dependencies.\n\n'
        'Generated by tool/generate_notices.dart; do not edit by hand.\n'
        '${inputFingerprints(package)}\n'
        'Target: $target\nRust: $rustVersion ($rustCommit)\n'
        'Native coverage: all ${crates.length} registry packages in Cargo.lock,\n'
        'including build/proc-macro and conservatively other-target dependencies.\n'
        'No native lock crates are excluded. ADELE itself is not third-party.\n'
        'Runtime coverage: pinned std with backtrace/panic-unwind, Linux normal\n'
        'and build edges (not dev/test edges), ${runtimeCrates.length} registry crates,\n'
        'plus in-tree std, compiler-builtins/libm, backtrace, and SIMD notices.\n'
        'Runtime other-target crates, compiler tools, docs, and fonts are excluded.\n'
        'Source comments are retained conservatively within included crates.\n'
        'MIT is selected where offered (adler2 uses 0BSD); additional terms apply.\n'
        'Full supplemental notices may describe unselected alternative terms.\n\n'
        'Flutter collects this package LICENSE into NOTICES.Z. Keep that asset\n'
        'in application distributions. Standalone native-library distributions\n'
        'must carry this file. System libraries are not vendored here; review\n'
        'their distribution terms separately if bundling them. This inventory\n'
        'does not establish complete application redistribution clearance.\n',
  ];
  for (final crate in crates) {
    sections.add(_crateSection(crate, checksums, 'Cargo.lock'));
  }
  for (final crate in runtimeCrates) {
    sections.add(
      _crateSection(crate, runtimeChecksums, 'Rust $rustVersion runtime'),
    );
  }

  final runtimeText = StringBuffer()
    ..writeln('Rust $rustVersion in-tree runtime\n')
    ..writeln(
      'Source: rust-lang/rust $rustCommit (installed rust-src/rust-docs)',
    )
    ..writeln('Declared: MIT OR Apache-2.0, with exceptions below.')
    ..writeln(
      'Selected: MIT; Unicode-3.0; compiler-builtins MIT AND '
      'Apache-2.0 WITH LLVM-exception; embedded BSD and other permissive notices.',
    )
    ..writeln('compiler_builtins version: 0.1.160; not a registry archive.');
  final copyright = _readNotice(File('${docs.path}/COPYRIGHT-library.html'));
  final inTree = copyright.substring(
    copyright.indexOf('<h2 id="longer-version">'),
    copyright.indexOf('<h2 id="out-of-tree-dependencies">'),
  );
  // Keep upstream attribution rather than filling a generic copyright template.
  _append(
    runtimeText,
    'COPYRIGHT-library.html (in-tree attribution)',
    _htmlText(inTree),
  );
  _append(
    runtimeText,
    'Rust MIT permission text',
    _readNotice(
      File('${docs.path}/html/static.files/LICENSE-MIT-23f18e03.txt'),
    ),
  );
  _append(
    runtimeText,
    'Unicode-3.0',
    _readNotice(File('${docs.path}/licenses/Unicode-3.0.txt')),
  );
  // Fuchsia's complete, attributed BSD text is retained from its source comment
  // below, not the generic BSD template shipped in rust-docs/licenses.
  for (final path in [
    'backtrace/LICENSE-MIT',
    'stdarch/LICENSE-MIT',
    'portable-simd/LICENSE-MIT',
    'compiler-builtins/LICENSE.txt',
    'compiler-builtins/libm/LICENSE.txt',
  ]) {
    _append(
      runtimeText,
      'rust-src/library/$path',
      _readNotice(File('${library.path}/$path')),
    );
  }
  for (final path in [
    'alloc/src',
    'core/src',
    'std/src',
    'std_detect/src',
    'panic_unwind/src',
    'unwind/src',
    'backtrace/src',
    'stdarch/crates/core_arch/src',
    'portable-simd/crates',
    'compiler-builtins/compiler-builtins/src',
    'compiler-builtins/libm/src',
  ]) {
    for (final entry in sourceNotices(
      Directory('${library.path}/$path'),
    ).entries) {
      _append(runtimeText, 'rust-src/library/$path/${entry.key}', entry.value);
    }
  }
  sections.add(runtimeText.toString());
  // Normalize line endings/trailing whitespace, never attribution or wording.
  return '${sections.map((s) => s.trimRight()).join(noticeSeparator).split('\n').map((line) => line.trimRight()).join('\n')}\n';
}

Map<String, dynamic> _metadata(Directory directory, {bool runtime = false}) =>
    jsonDecode(
          _run(
            'rustup',
            [
              'run',
              rustVersion,
              'cargo',
              'metadata',
              '--locked',
              '--format-version',
              '1',
              if (runtime) ...[
                '--filter-platform',
                target,
                '--features',
                'std/backtrace,std/panic-unwind',
              ],
            ],
            directory: directory,
            environment: runtime ? {'RUSTC_BOOTSTRAP': '1'} : null,
          ),
        )
        as Map<String, dynamic>;

int _comparePackages(Map<String, dynamic> a, Map<String, dynamic> b) =>
    '${a['name']} ${a['version']}'.compareTo('${b['name']} ${b['version']}');

String inputFingerprints(Directory package) => [
  for (final path in [
    'native/Cargo.lock',
    'native/Cargo.toml',
    'native/rust-toolchain',
    'tool/generate_notices.dart',
  ])
    '$path SHA256: ${sha256File(File('${package.path}/$path'))}',
].join('\n');

String sha256File(File file) => _run('sha256sum', [file.path]).split(' ').first;

Map<String, String> lockChecksums(String lock) {
  final result = <String, String>{};
  for (final block in lock.split('[[package]]').skip(1)) {
    String? field(String name) => RegExp(
      '^$name = "([^"]+)"',
      multiLine: true,
    ).firstMatch(block)?.group(1);
    if (field('source') == null) continue;
    if (field('source') !=
            'registry+https://github.com/rust-lang/crates.io-index' ||
        !RegExp(r'^[a-f0-9]{64}$').hasMatch(field('checksum') ?? '')) {
      throw StateError('Unsupported source or missing checksum in Cargo.lock.');
    }
    final key = '${field('name')} ${field('version')}';
    if (result.containsKey(key)) {
      throw StateError('Duplicate locked crate $key');
    }
    result[key] = field('checksum')!;
  }
  return result;
}

String selectedLicense(String declared) => switch (declared) {
  'MIT' ||
  'MIT OR Apache-2.0' ||
  'Apache-2.0 OR MIT' ||
  'MIT/Apache-2.0' ||
  'Unlicense OR MIT' ||
  'MIT OR Zlib OR Apache-2.0' ||
  'MIT OR Apache-2.0 OR LGPL-2.1-or-later' ||
  'Apache-2.0 WITH LLVM-exception OR Apache-2.0 OR MIT' => 'MIT',
  '(MIT OR Apache-2.0) AND Unicode-3.0' => 'MIT AND Unicode-3.0',
  '0BSD OR MIT OR Apache-2.0' => '0BSD',
  'Zlib' => 'Zlib',
  _ => throw StateError('Unsupported/unreviewed license: $declared'),
};

String _crateSection(
  Map<String, dynamic> crate,
  Map<String, String> checksums,
  String scope,
) {
  final name = crate['name'] as String;
  final key = '$name ${crate['version']}';
  final checksum = checksums[key];
  if (checksum == null ||
      crate['source'] !=
          'registry+https://github.com/rust-lang/crates.io-index') {
    throw StateError('Missing locked registry identity: $key');
  }
  final declared = crate['license'] as String? ?? '';
  final selected = selectedLicense(declared);
  final dir = File(crate['manifest_path'] as String).parent;
  final notices = crateNotices(dir, selected, name: name);
  final result = StringBuffer()
    ..writeln('$key ($scope)\n')
    ..writeln('Crate: $name\nVersion: ${crate['version']}')
    ..writeln('Checksum (crates.io SHA256): $checksum')
    ..writeln('Source: https://crates.io/crates/$name/${crate['version']}')
    ..writeln('Declared license: $declared\nSelected option: $selected');
  for (final notice in notices.entries) {
    _append(result, notice.key, notice.value);
  }
  return result.toString();
}

Map<String, String> crateNotices(
  Directory dir,
  String selected, {
  required String name,
}) {
  final candidates = selected == '0BSD'
      ? ['LICENSE-0BSD']
      : selected == 'Zlib'
      ? ['LICENSE']
      : name == 'r-efi'
      ? ['AUTHORS']
      : ['LICENSE-MIT', 'license-mit', 'LICENSE-MIT.md', 'LICENSE'];
  final primary = candidates.where((p) => File('${dir.path}/$p').existsSync());
  if (primary.isEmpty) throw StateError('Missing $selected license: $name');
  final text = _readNotice(File('${dir.path}/${primary.first}'));
  final words = text.replaceAll(RegExp(r'\s+'), ' ');
  if (selected.startsWith('MIT') &&
      (!words.contains('Permission is hereby granted, free of charge') ||
          !words.contains('THE SOFTWARE IS PROVIDED'))) {
    throw StateError('Missing full MIT text: $name/${primary.first}');
  }
  final result = <String, String>{primary.first: text};
  final requiredExtras = <String>[
    if (selected.contains('Unicode-3.0')) 'LICENSE-UNICODE',
    if (['atomic-waker', 'futures-lite', 'parking'].contains(name))
      'LICENSE-THIRD-PARTY',
    if (['rustix', 'linux-raw-sys'].contains(name)) 'COPYRIGHT',
    if (name == 'uds_windows') 'THIRDPARTYNOTICES',
    if (name == 'tracing-core') 'src/spin/LICENSE',
    if (name == 'memchr') 'COPYING',
  ];
  for (final path in requiredExtras) {
    result[path] = _readNotice(File('${dir.path}/$path'));
  }
  // Reject newly encountered legal files rather than silently overlooking them.
  final alternatives = {
    if (selected == '0BSD') ...['LICENSE-MIT', 'LICENSE-APACHE'],
    'LICENSE-APACHE',
    'LICENSE-APACHE.md',
    'license-apache-2.0',
    'LICENSE-Apache-2.0_WITH_LLVM-exception',
    'UNLICENSE',
    'LICENSE-ZLIB.md',
    ...candidates,
  };
  for (final file
      in dir.listSync(recursive: true, followLinks: false).whereType<File>()) {
    final path = file.path.substring(dir.path.length + 1);
    final basename = file.uri.pathSegments.last;
    if (!RegExp(
      r'^(licen[cs]e|copying|copyright|notice|third.?party)',
      caseSensitive: false,
    ).hasMatch(basename)) {
      continue;
    }
    if (!result.containsKey(path) && !alternatives.contains(path)) {
      // typenum's LICENSE is just its already-recorded SPDX expression.
      if (name == 'typenum' &&
          path == 'LICENSE' &&
          file.readAsStringSync().trim() == 'MIT OR Apache-2.0') {
        continue;
      }
      throw StateError('Unreviewed notice file: $name/$path');
    }
  }
  for (final entry in sourceNotices(Directory('${dir.path}/src')).entries) {
    result['src/${entry.key}'] = entry.value;
  }
  return result;
}

Map<String, String> sourceNotices(Directory directory) {
  if (!directory.existsSync()) {
    throw StateError('Missing source notice directory: ${directory.path}');
  }
  final files =
      directory
          .listSync(recursive: true, followLinks: false)
          .whereType<File>()
          .where((f) => f.path.endsWith('.rs'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  final result = <String, String>{};
  final comments = RegExp(
    r'(?:^[ \t]*//[^\n]*(?:\n|$))+|/\*[\s\S]*?\*/',
    multiLine: true,
  );
  for (final file in files) {
    final blocks = comments
        .allMatches(file.readAsStringSync())
        .map((m) => m.group(0)!.trimRight())
        .where(
          (s) => RegExp(
            r'copyright[^\n]*(?:\d|\(c\)|\u00a9)',
            caseSensitive: false,
          ).hasMatch(s),
        )
        .toSet();
    if (blocks.isNotEmpty) {
      result['${file.path.substring(directory.path.length + 1)} '
          '(embedded source notices)'] = blocks.join(
        '\n\n',
      );
    }
  }
  return result;
}

void _append(StringBuffer buffer, String label, String text) {
  buffer
    ..writeln('\n--- $label ---\n')
    ..writeln(text.trimRight());
}

String _readNotice(File file) {
  final text = file.readAsStringSync();
  if (text.trim().isEmpty) throw StateError('Empty notice: ${file.path}');
  if (RegExp(
    r'<year>|<owner>|<copyright holders>|\[year\]|\[fullname\]',
    caseSensitive: false,
  ).hasMatch(text)) {
    throw StateError('Unresolved copyright template: ${file.path}');
  }
  if (text.contains(noticeSeparator)) {
    throw StateError(
      'Upstream notice conflicts with Flutter separator: ${file.path}',
    );
  }
  return text;
}

String _htmlText(String html) {
  var text = html.replaceAll(RegExp(r'<[^>]+>'), '');
  text = text.replaceAllMapped(
    RegExp(r'&#(\d+);'),
    (m) => String.fromCharCode(int.parse(m.group(1)!)),
  );
  for (final entity in {
    '&lt;': '<',
    '&gt;': '>',
    '&quot;': '"',
    '&amp;': '&',
  }.entries) {
    text = text.replaceAll(entity.key, entity.value);
  }
  return text
      .split('\n')
      .map((l) => l.trim())
      .join('\n')
      .replaceAll(RegExp(r'\n{3,}'), '\n\n')
      .trim();
}

String _run(
  String executable,
  List<String> arguments, {
  Directory? directory,
  Map<String, String>? environment,
}) {
  final result = Process.runSync(
    executable,
    arguments,
    workingDirectory: directory?.path,
    environment: environment,
  );
  if (result.exitCode != 0) {
    throw StateError(
      '$executable ${arguments.join(' ')} failed: ${result.stderr}',
    );
  }
  return result.stdout as String;
}

def native(source):
    return ("// Generated by ADELE contract_codegen (native transport).\n\n"
            f"part of '{source.name}';\n// non-ASCII: \u2603; preserve trailing CRLF\r\n").encode()


def write_zip(path, entries):
    with warnings.catch_warnings(), zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as archive:
        warnings.simplefilter('ignore', UserWarning)  # Deliberate duplicate member.
        for name, data in entries:
            if isinstance(name, str):
                name = zipfile.ZipInfo(name)
                name.external_attr = (stat.S_IFREG | 0o644) << 16
                name.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(name, data)


class TempCheckout(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.temp = Path(tmp.name)
        self.repo = self.temp / 'checkout'
        self.prepare_checkout()
        self.addCleanup(os.chdir, Path.cwd())
        os.chdir(self.repo)
        self.log = io.StringIO()
        self.enter(contextlib.redirect_stdout(self.log))

    def enter(self, context):
        result = context.__enter__()
        self.addCleanup(context.__exit__, None, None, None)
        return result


class TransportTest(TempCheckout):
    def prepare_checkout(self):
        self.repo.mkdir()

    def setUp(self):
        super().setUp()
        self.rows = [(Path(name + '.dart'), Path(name + '.g.dart')) for name in ('first', 'last')]
        ident = {'commit': 'local'}
        self.enter(patch.object(handoff, 'identity', return_value=(ident, self.rows)))
        self.enter(patch.object(handoff, 'require_clean'))
        entries = []
        for source, target in self.rows:
            data = native(source)
            entries.append(dict(path=str(target), sha256=hashlib.sha256(data).hexdigest(),
                                size=len(data), text=data.decode()))
        self.bundle = {'identity': ident, 'version': 1, 'outputs': entries}
        self.raw = json.dumps(self.bundle).encode()
        self.zip = self.temp / 'contracts.zip'

    def rejects(self):
        with self.assertRaises((ValueError, zipfile.BadZipFile, OSError)):
            handoff.consume(self.zip)
        self.assertFalse(self.rows[0][1].exists(), 'wrote the first part before failure')

    def test_raw_zip_is_one_regular_bounded_entry(self):
        good = ('contracts.json', self.raw)
        for entries in ([], [good, good], [good, ('extra', b'')], [('../contracts.json', self.raw)],
                        [('contracts.json/', self.raw)], [('contracts.json', b'x' * (handoff.MAX_JSON + 1))],
                        [('contracts.json', b'{"version":1,' + self.raw[1:])]):
            with self.subTest(names=[str(e[0]) for e in entries]):
                write_zip(self.zip, entries)
                self.rejects()
        for mode in (0, stat.S_IFLNK, stat.S_IFIFO, stat.S_IFDIR, stat.S_IFCHR):
            info = zipfile.ZipInfo('contracts.json')
            info.external_attr = (mode | 0o644) << 16
            write_zip(self.zip, [(info, self.raw)])
            self.rejects()
        write_zip(self.zip, [good])
        self.zip.write_bytes(self.zip.read_bytes()[:-20])
        self.rejects()
        self.zip.write_bytes(bytes(handoff.MAX_ZIP + 1))
        self.rejects()
        self.zip.unlink()
        self.zip.symlink_to(self.temp / 'missing')
        self.rejects()

    def test_identity_inventory_and_late_payload_errors_precede_writes(self):
        for mutation in (lambda b: b.update(version=True), lambda b: b['identity'].update(attempt='old'),
                         lambda b: b['outputs'].pop(), lambda b: b['outputs'].append(b['outputs'][0]),
                         lambda b: b['outputs'][-1].update(path='../outside'),
                         lambda b: b['outputs'][-1].update(path=b['outputs'][0]['path']),
                         lambda b: b['outputs'][-1].update(text='altered'),
                         lambda b: b['outputs'][-1].update(sha256='0' * 64),
                         lambda b: b['outputs'][-1].update(size=False)):
            bundle = copy.deepcopy(self.bundle)
            mutation(bundle)
            write_zip(self.zip, [('contracts.json', json.dumps(bundle))])
            self.rejects()

    def test_confined_destination_types_and_readback(self):
        write_zip(self.zip, [('contracts.json', self.raw)])
        last = self.rows[-1][1]
        outside = self.temp / 'untouched'
        outside.write_bytes(b'old')
        for create in (lambda: last.symlink_to(outside), lambda: os.link(outside, last), lambda: os.mkfifo(last)):
            create()
            self.rejects()
            last.unlink()
            self.assertEqual(outside.read_bytes(), b'old')
        with patch.object(Path, 'replace', return_value=None), self.assertRaises(OSError):
            handoff.consume(self.zip)  # A failed materialization must never report admission.
        self.assertEqual(list(Path('.').iterdir()), [])


class IdentityAndGenerationTest(TempCheckout):
    def prepare_checkout(self):
        # Only the checkout/index and tracked configuration are real. Never run
        # pub, reach a network, create a commit or need a developer installation.
        subprocess.run(['git', 'clone', '-q', '--shared', str(REPO), str(self.repo)], check=True)

    def setUp(self):
        super().setUp()
        ref = 'refs/pull/7/merge'
        self.sdk = self.temp / 'sdk'
        (self.sdk / 'bin').mkdir(parents=True)
        cache = self.temp / 'cache'
        (cache / 'hosted/pub.dev/example-1').mkdir(parents=True)
        self.enter(patch.dict(os.environ, GITHUB_ACTIONS='true', RUNNER_OS='Linux', GITHUB_REPOSITORY='org/repo',
                              GITHUB_JOB='discover-test-targets', GITHUB_EVENT_NAME='pull_request', GITHUB_REF=ref,
                              GITHUB_WORKFLOW_REF=f'org/repo/.github/workflows/ci.yaml@{ref}', GITHUB_RUN_ID='9',
                              GITHUB_RUN_ATTEMPT='1', GITHUB_SHA=handoff.git('rev-parse', 'HEAD'),
                              GITHUB_WORKSPACE=str(self.repo), RUNNER_TEMP=str(self.temp), FLUTTER_ROOT=str(self.sdk),
                              PUB_CACHE=str(cache), PATH=f"{self.sdk}/bin:{os.environ['PATH']}"))
        pins = json.loads(Path('toolchain.json').read_bytes())
        channel = Path('.tool-versions').read_text().split()[1].split('-')[-1]
        self.report = dict(frameworkVersion=pins['flutter'], frameworkRevision=pins['flutterRevision'],
                           engineRevision=pins['engineRevision'], dartSdkVersion=pins['dart'],
                           flutterRoot=str(self.sdk), channel=channel)
        self.sources = [Path(line.split('- ', 1)[1]) for line in Path('contract_codegen.yaml').read_text().splitlines()
                        if line.strip().startswith('- ')]
        self.pc = Path('.dart_tool/package_config.json')
        self.pc.parent.mkdir()
        self.cfg = dict(configVersion=2, generator='pub', generatorVersion=pins['dart'], flutterVersion=pins['flutter'],
                        flutterRoot=self.sdk.as_uri(), pubCache=cache.as_uri(), packages=[
                            dict(name='test', rootUri='../', languageVersion='3.0', packageUri='lib/'),
                            dict(name='example', rootUri=(cache / 'hosted/pub.dev/example-1').as_uri(),
                                 languageVersion='3.0', packageUri='lib/')])
        self.pc.write_text(json.dumps(self.cfg))
        self.pg = self.pc.with_name('package_graph.json')
        self.graph = dict(configVersion=1, roots=['test'], packages=[dict(name='test', dependencies=['example']),
                                                                     dict(name='example', dependencies=[])])
        self.pg.write_text(json.dumps(self.graph))
        for name in ('dart', 'flutter'):
            exe = self.sdk / 'bin' / name
            exe.touch(mode=0o755)
        self.generated = 0
        run = subprocess.run

        def local_command(args, **kwargs):
            if args == ['flutter', '--version', '--machine']:
                stdout = json.dumps(self.report).encode()
            elif args == ['dart', '--version']:
                stdout = f'Dart SDK version: {pins["dart"]} (stable) on "linux_x64"'
            elif args == ['dart', 'tools/adele.dart', 'generate']:
                self.generated += 1
                for source in self.sources:
                    source.with_suffix('.g.dart').write_bytes(native(source))
                stdout = b''
            else:
                self.assertEqual(args[0], 'git', 'unexpected tool invocation')
                return run(args, **kwargs)
            return subprocess.CompletedProcess(args, 0, stdout)

        self.enter(patch.object(subprocess, 'run', side_effect=local_command))
        self.artifact = self.temp / 'contracts.json'

    def test_produce_raw_zip_consume_and_repeat(self):
        first = self.sources[0].with_suffix('.g.dart')
        first.touch()
        with self.assertRaisesRegex(ValueError, 'all configured parts absent'):
            handoff.produce(self.artifact)
        self.assertEqual(self.generated, 0)
        first.unlink()
        handoff.produce(self.artifact)
        self.assertEqual(self.generated, 1)
        archive = self.temp / 'contracts.zip'
        with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
            z.write(self.artifact, 'contracts.json')
        targets = [source.with_suffix('.g.dart') for source in self.sources]
        for target in targets:
            target.unlink()
        self.cfg['packages'].reverse()  # pub ordering and machine paths are not identities.
        new_cache = self.temp / 'relocated'
        Path(os.environ['PUB_CACHE']).rename(new_cache)
        os.environ['PUB_CACHE'] = str(new_cache)
        self.cfg.update(pubCache=new_cache.as_uri())
        self.cfg['packages'][0]['rootUri'] = (new_cache / 'hosted/pub.dev/example-1').as_uri()
        self.pc.write_text(json.dumps(self.cfg))
        os.environ['GITHUB_JOB'] = 'test-target'
        for key, value in [('GITHUB_RUN_ATTEMPT', '2'), ('GITHUB_RUN_ID', '42')]:
            with patch.dict(os.environ, {key: value}), self.assertRaisesRegex(ValueError, 'identity'):
                handoff.consume(archive)
        self.graph['packages'][0]['dependencies'].clear()
        self.pg.write_text(json.dumps(self.graph))
        with self.assertRaisesRegex(ValueError, 'identity'):
            handoff.consume(archive)
        self.assertFalse(first.exists())
        self.graph['packages'][0]['dependencies'].append('example')
        self.pg.write_text(json.dumps(self.graph))
        handoff.consume(archive)
        self.assertEqual([p.read_bytes() for p in targets], [native(s) for s in self.sources])
        times = [p.stat().st_mtime_ns for p in targets]
        handoff.consume(archive)
        self.assertEqual([p.stat().st_mtime_ns for p in targets], times)
        self.assertNotIn('preserve trailing CRLF', self.log.getvalue())

    def test_wrong_workflow_toolchain_dirty_checkout_and_ignored_shadows(self):
        for key, value in [('GITHUB_EVENT_NAME', 'workflow_dispatch'), ('GITHUB_JOB', 'test-target'),
                           ('GITHUB_WORKFLOW_REF', 'org/repo/.github/workflows/not-ci.yaml@refs/pull/7/merge'),
                           ('GITHUB_REPOSITORY', 'other/repo'), ('GITHUB_SHA', '0' * 40), ('GITHUB_ACTIONS', 'false')]:
            with self.subTest(key=key), patch.dict(os.environ, {key: value}), self.assertRaises(ValueError):
                handoff.produce(self.artifact)
        with patch.dict(self.report, engineRevision='0' * 40), self.assertRaisesRegex(ValueError, 'toolchain'):
            handoff.produce(self.artifact)
        with patch.dict(self.cfg, generatorVersion='wrong'):
            self.pc.write_text(json.dumps(self.cfg))
            with self.assertRaisesRegex(ValueError, 'provider mismatch'):
                handoff.produce(self.artifact)
        self.pc.write_text(json.dumps(self.cfg))
        for directory in (self.sources[-1].parent, Path('packages/contract_codegen/bin'), Path('tools')):
            shadow = directory / '.dart_tool/package_config.json'
            shadow.parent.mkdir()
            shadow.write_bytes(self.pc.read_bytes())
            with self.assertRaisesRegex(ValueError, 'unexpected resolver'):
                handoff.produce(self.artifact)
            shadow.unlink()
        with Path('pubspec.lock').open('ab') as lock:
            lock.write(b'\n')
        with self.assertRaisesRegex(ValueError, 'dirty checkout'):
            handoff.produce(self.artifact)
        self.assertEqual(self.generated, 0)
        self.assertFalse(self.artifact.exists())

    def test_producer_rechecks_identity_after_generation(self):
        identity = handoff.identity

        def during_generation(mode):
            if self.generated:
                self.cfg['packages'][0]['languageVersion'] = '2.19'
                self.pc.write_text(json.dumps(self.cfg))
            return identity(mode)

        with patch.object(handoff, 'identity', side_effect=during_generation), self.assertRaisesRegex(ValueError, 'changed'):
            handoff.produce(self.artifact)
        self.assertEqual(self.generated, 1)
        self.assertFalse(self.artifact.exists())


